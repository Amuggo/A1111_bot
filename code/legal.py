"""
Условия использования, дисклеймеры и условия подписки (HTML для Telegram).

Тексты условий коротко и по-человечески. Контакты и версия задаются через .env:
  SUPPORT_CONTACT — контакт поддержки (@username или e-mail)
  TERMS_VERSION   — версия условий; при её изменении все пользователи примут условия заново
  MIN_AGE         — минимальный возраст (по умолчанию 18)
"""

import os
import html

TERMS_VERSION = os.environ.get("TERMS_VERSION", "1").strip() or "1"
MIN_AGE = os.environ.get("MIN_AGE", "18").strip() or "18"


def _support() -> str:
    contact = os.environ.get("SUPPORT_CONTACT", "").strip()
    return html.escape(contact) if contact else "команда /paysupport"


# Короткий дисклеймер — под каждой задачей генерации (одна строка).
SHORT_DISCLAIMER = "⚠️ <i>Изображение создано ИИ. Вы отвечаете за промпт и использование результата.</i>"

# Усиленный дисклеймер — когда в генерации участвует лицо (FaceID/замена).
FACE_DISCLAIMER = ("⚠️ <i>Изображение создано ИИ с использованием лица. Используйте только свои фото или фото "
                   "людей, давших согласие. Выдавать результат за реальное фото запрещено.</i>")


def disclaimer(face: bool = False) -> str:
    return FACE_DISCLAIMER if face else SHORT_DISCLAIMER


def terms_text() -> str:
    return (
        "📜 <b>Условия использования</b>\n\n"
        "1. Бот рисует картинки с помощью ИИ, результат бывает неточным.\n"
        f"2. Пользоваться можно только с {MIN_AGE} лет.\n"
        "3. Нельзя создавать сексуальный контент с несовершеннолетними, а также изображения, которыми можно навредить людям или обмануть их.\n"
        "4. Лица: загружайте только свои фото или фото тех, кто разрешил.\n"
        "5. За свои запросы и за то, как используете результат, отвечаете вы. За нарушения можно потерять доступ."
    )


def subscription_terms_text(products: dict, welcome: str, cost_gen: str, cost_face: str, cost_up: str) -> str:
    """Условия подписки и токенов; цены берутся из настроек, чтобы текст не расходился с реальностью."""
    prices = "\n".join(f"• {html.escape(p['title'])} — {p['stars']}⭐" for p in products.values())
    return (
        "💳 <b>Условия подписки</b>\n\n"
        f"🪙 <b>Токены</b> — валюта бота. При первом входе дарим {welcome}.\n"
        f"Обычная генерация — {cost_gen}, с лицом — {cost_face}, апскейл — {cost_up}.\n"
        "<b>Pro:</b> токены не тратятся, плюс тонкие настройки генерации.\n\n"
        f"{prices}\n\n"
        "• Это разовая покупка, автопродления нет.\n"
        "• Если купить ещё раз, срок продлится.\n"
        "• Когда срок закончится, вы вернётесь на Free, а токены, настройки и лица останутся.\n"
        "• Завершить подписку раньше можно в «💳 Подписка», но остаток срока сгорит.\n"
        "• Если задача не встала в очередь, токены возвращаются.\n\n"
        f"Вопросы по оплате и возврату: {_support()} (укажите номер платежа из чека)."
    )
